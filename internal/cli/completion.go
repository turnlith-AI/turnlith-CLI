// flagValues lists the fixed choices of value flags.
var flagValues = map[string][]string{
	"--permission-mode": {"normal", "auto", "plan", "yolo"},
	"--output-format":   {"text", "json", "stream-json"},
	"--effort":          {"none", "minimal", "low", "medium", "high", "xhigh"},
}

var shortFlags = map[string]string{"--print": "-p", "--continue": "-c", "--help": "-h", "--version": "-v"}

type commandInfo struct{ name, help string }

var topCommands = []commandInfo{
	{"agents", "list or create the workspace's agents"},
	{"configure", "save the server URL and api key"},
	{"doctor", "check the connection, key, agent and local tools"},
	{"install", "wire the agents into coding clients (opencode, pi, continue, cursor, cline)"},
	{"uninstall", "remove the turnlith entries from those clients"},
	{"completion", "print a shell completion script"},
	{"help", "show help"},
	{"version", "print the version"},
}

func allLongFlags() []string {
	seen := map[string]bool{}
	for name := range boolFlags {
		if strings.HasPrefix(name, "--") {
			seen[name] = true
		}
	}
	for name := range valueFlags {
		seen[name] = true
	}
	out := make([]string, 0, len(seen))
	for name := range seen {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

// clientChoices are the names offered after install/uninstall.
func clientChoices() []string { return append(harness.Names(), "all") }

func commandNames() []string {
	names := make([]string, len(topCommands))
	for i, c := range topCommands {
		names[i] = c.name
	}
	return names
}

// completionScript renders the completion script for a shell, generated from
// the same tables the parser uses so it cannot drift from the real flags.
func completionScript(shell string) (string, error) {
	switch shell {
	case "bash":
		return bashCompletion(), nil
	case "zsh":
		return zshCompletion(), nil
	case "fish":
		return fishCompletion(), nil
	}
	return "", fmt.Errorf("unknown shell %q — supported: bash, zsh, fish", shell)
}

func bashCompletion() string {
	var b strings.Builder
	b.WriteString("# bash completion for tlc — generated by `tlc completion bash`\n")
	b.WriteString("# install: tlc completion bash > ~/.local/share/bash-completion/completions/tlc\n")
	b.WriteString("_tlc() {\n\tlocal cur prev\n\tcur=\"${COMP_WORDS[COMP_CWORD]}\"\n\tprev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n\tCOMPREPLY=()\n\tcase \"$prev\" in\n")
	flags := allLongFlags()
	for _, f := range flags {
		if vals, ok := flagValues[f]; ok {
			fmt.Fprintf(&b, "\t\t%s) COMPREPLY=( $(compgen -W %q -- \"$cur\") ); return 0 ;;\n", f, strings.Join(vals, " "))
		}
	}
	b.WriteString("\tesac\n")
	shorts := []string{}
	for _, f := range flags {
		if s, ok := shortFlags[f]; ok {
			shorts = append(shorts, s)
		}
	}
	sort.Strings(shorts)
	fmt.Fprintf(&b, "\tif [[ \"$cur\" == -* ]]; then\n\t\tCOMPREPLY=( $(compgen -W %q -- \"$cur\") )\n\t\treturn 0\n\tfi\n",
		strings.Join(append(flags, shorts...), " "))
	fmt.Fprintf(&b, "\tif [[ $COMP_CWORD -eq 1 ]]; then\n\t\tCOMPREPLY=( $(compgen -W %q -- \"$cur\") )\n\t\treturn 0\n\tfi\n", strings.Join(commandNames(), " "))
	b.WriteString("\tcase \"${COMP_WORDS[1]}\" in\n")
	b.WriteString("\t\tagents) COMPREPLY=( $(compgen -W \"list create\" -- \"$cur\") ) ;;\n")
	fmt.Fprintf(&b, "\t\tinstall|uninstall) COMPREPLY=( $(compgen -W %q -- \"$cur\") ) ;;\n", strings.Join(clientChoices(), " "))
	b.WriteString("\t\tcompletion) COMPREPLY=( $(compgen -W \"bash zsh fish\" -- \"$cur\") ) ;;\n")
	b.WriteString("\tesac\n}\ncomplete -F _tlc tlc\n")
	return b.String()
}

func zshQuote(s string) string {
	s = strings.ReplaceAll(s, `'`, `'\''`)
	s = strings.NewReplacer("[", `\[`, "]", `\]`, ":", `\:`).Replace(s)
	return s
}

func zshCompletion() string {
	var b strings.Builder
	b.WriteString("#compdef tlc\n# zsh completion for tlc — generated by `tlc completion zsh`\n")
	b.WriteString("# install: tlc completion zsh > \"${fpath[1]}/_tlc\"  (then restart your shell)\n\n")
	b.WriteString("_tlc() {\n\tlocal context state state_descr line\n\ttypeset -A opt_args\n\t_arguments -C \\\n")
	for _, f := range allLongFlags() {
		spec := f
		if s, ok := shortFlags[f]; ok {
			spec = fmt.Sprintf("(%s %s)'{%s,%s}'", s, f, s, f)
		} else {
			spec = "'" + f
		}
		spec += fmt.Sprintf("[%s]", zshQuote(flagHelp[f]))
		if vals, ok := flagValues[f]; ok {
			spec += fmt.Sprintf(":value:(%s)", strings.Join(vals, " "))
		} else if _, isValue := valueFlags[f]; isValue {
			spec += ":value:"
		}
		// closing quote: the {-p,--print} form already closed its own
		if strings.HasPrefix(spec, "(") {
			spec = strings.Replace(spec, "'{", "'{", 1)
			b.WriteString("\t\t'" + spec + "' \\\n")
		} else {
			b.WriteString("\t\t" + spec + "' \\\n")
		}
	}
	b.WriteString("\t\t'1: :->command' \\\n\t\t'*:: :->args'\n\n")
	b.WriteString("\tcase $state in\n\t\tcommand)\n\t\t\t_values 'command'")
	for _, c := range topCommands {
		fmt.Fprintf(&b, " '%s[%s]'", c.name, zshQuote(c.help))
	}
	b.WriteString(" ;;\n\t\targs)\n\t\t\tcase $words[1] in\n")
	b.WriteString("\t\t\t\tagents) _values 'subcommand' list create ;;\n")
	fmt.Fprintf(&b, "\t\t\t\tinstall|uninstall) _values 'client' %s ;;\n", strings.Join(clientChoices(), " "))
	b.WriteString("\t\t\t\tcompletion) _values 'shell' bash zsh fish ;;\n")
	b.WriteString("\t\t\tesac ;;\n\tesac\n}\n\n_tlc \"$@\"\n")
	return b.String()
}

func fishQuote(s string) string { return strings.ReplaceAll(s, `'`, `\'`) }

func fishCompletion() string {
	var b strings.Builder
	b.WriteString("# fish completion for tlc — generated by `tlc completion fish`\n")
	b.WriteString("# install: tlc completion fish > ~/.config/fish/completions/tlc.fish\n")
	b.WriteString("complete -c tlc -f\n")
	for _, c := range topCommands {
		fmt.Fprintf(&b, "complete -c tlc -n __fish_use_subcommand -a %s -d '%s'\n", c.name, fishQuote(c.help))
	}
	b.WriteString("complete -c tlc -n '__fish_seen_subcommand_from agents' -a 'list create'\n")
	fmt.Fprintf(&b, "complete -c tlc -n '__fish_seen_subcommand_from install uninstall' -a '%s'\n", strings.Join(clientChoices(), " "))
	b.WriteString("complete -c tlc -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish'\n")
	for _, f := range allLongFlags() {
		line := "complete -c tlc"
		if s, ok := shortFlags[f]; ok {
			line += " -s " + strings.TrimPrefix(s, "-")
		}
		line += " -l " + strings.TrimPrefix(f, "--")
		if vals, ok := flagValues[f]; ok {
			line += fmt.Sprintf(" -x -a '%s'", strings.Join(vals, " "))
		} else if _, isValue := valueFlags[f]; isValue {
			line += " -r"
		}
		fmt.Fprintf(&b, "%s -d '%s'\n", line, fishQuote(flagHelp[f]))
	}
	return b.String()
}

// runCompletion is `tlc completion <shell>`.
func runCompletion(shell string) int {
	if shell == "" {
		fmt.Fprintln(os.Stderr, "usage: tlc completion bash|zsh|fish")
		return 2
	}
	script, err := completionScript(shell)
	if err != nil {
		fmt.Fprintf(os.Stderr, "tlc: %v\n", err)
		return 2
	}
	fmt.Print(script)
	return 0
}
